import { check, fresh, modules } from "./compare-core.mjs";

// this isolated bridge selects a native entry export; it never wraps a generated import.
export function ownedContext(artifact, p, host, mode) {
  check(["checked", "owned"].includes(mode), "explicit checked/owned mode");
  check(WebAssembly.Module.imports(artifact.module).every(item => item.module === "ring3_observability" && item.name === "now_ns" && item.kind === "function"),
    "engine transitive imports contain only the explicitly pure clock");
  check(WebAssembly.Module.exports(artifact.module).some(item => item.name === "ring3_abi_v1_begin_owned_execution_receipt" && item.kind === "function"),
    "C1 additive owned entry export is required before fixture setup");
  const c = fresh({ ...artifact, label: mode }, p, host);
  try {
    check(typeof SharedArrayBuffer === "undefined" || !(c.engine.memory.buffer instanceof SharedArrayBuffer),
      "this bounded ownership proof excludes shared external memory writers");
    c.mode = mode;
    c.pristine = Object.freeze({ ...c.engine.api });
    check(typeof c.pristine.begin_owned_execution_receipt === "function", "C1 additive owned entry export is required");
    if (mode === "owned") c.engine.api.begin_execution_receipt = c.pristine.begin_owned_execution_receipt;
    check(c.engine.api.begin_execution_receipt === c.pristine[mode === "owned" ? "begin_owned_execution_receipt" : "begin_execution_receipt"],
      "receipt selection is the original native Wasm export reference");
    return c;
  } catch (error) { c.engine.ok("close"); throw error; }
}

export async function ownedTopology(c) {
  const records = await modules(c);
  for (const record of records) for (const item of record.imports) {
    check(item.module === "env" && item.name === "memory" && item.kind === "memory" || item.module === "ring3" && item.kind === "function",
      "no opaque generated imports in owned comparison");
    if (item.module === "ring3") check(typeof c.pristine[item.name] === "function" && c.engine.api[item.name] === c.pristine[item.name],
      `generated import remains a direct pristine binding: ${item.name}`);
  }
  for (const name of ["guard_dispatch_entry", "find_installed_resident", "finish_execution_receipt"])
    check(c.engine.api[name] === c.pristine[name], `dispatcher/finish direct binding ${name}`);
  return { mode: c.mode, modules: records, owners: [...c.owners].map(([pc, u]) => [pc, String(u.id), u.slot, u.tier]),
    clock: "fresh() instantiates the original module with the literal known-pure now_ns: () => 0n" };
}

export function equalTopology(a, b) {
  check(JSON.stringify(a.modules) === JSON.stringify(b.modules), "C1 generated bytes, imports, unit identities and metadata are byte-identical");
  check(JSON.stringify(a.owners) === JSON.stringify(b.owners), "same warmed resident ownership topology");
}
