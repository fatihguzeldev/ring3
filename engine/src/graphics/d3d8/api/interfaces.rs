use crate::windows::com::InterfaceId;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum InterfaceKind {
    Direct3D = 1,
    Device = 2,
    Resource = 3,
    BaseTexture = 4,
    Texture = 5,
    CubeTexture = 6,
    VolumeTexture = 7,
    VertexBuffer = 8,
    IndexBuffer = 9,
    Surface = 10,
    Volume = 11,
    SwapChain = 12,
}

