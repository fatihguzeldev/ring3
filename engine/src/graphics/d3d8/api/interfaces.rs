    pub const ALL: [Self; 12] = [
        Self::Direct3D,
        Self::Device,
        Self::Resource,
        Self::BaseTexture,
        Self::Texture,
        Self::CubeTexture,
        Self::VolumeTexture,
        Self::VertexBuffer,
        Self::IndexBuffer,
        Self::Surface,
        Self::Volume,
        Self::SwapChain,
    ];

