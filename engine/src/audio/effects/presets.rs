use super::{EffectKind, Parameters};
use crate::audio::AudioError32;

impl Parameters {
    pub fn i3dl2_preset(index: u32) -> Result<Self, AudioError32> {
        let values = PRESETS
            .get(index as usize)
            .ok_or(AudioError32::InvalidRequest)?;
        let mut words = [
            -1000i32 as u32,
            values[0] as i32 as u32,
            0.0f32.to_bits(),
            values[1].to_bits(),
            values[2].to_bits(),
            values[3] as i32 as u32,
            values[4].to_bits(),
            values[5] as i32 as u32,
            values[6].to_bits(),
            values[7].to_bits(),
            values[8].to_bits(),
            5000.0f32.to_bits(),
        ];
        if index == 29 {
            words[1] = -200i32 as u32;
        }
        Ok(Self {
            kind: EffectKind::I3dl2Reverb,
            words,
        })
    }
}

