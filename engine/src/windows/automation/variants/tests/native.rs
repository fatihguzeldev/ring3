#[test]
fn native_fractional_scientific_text_preserves_significant_digits_before_fixed_promotion() {
    let inputs = [
        1.234567e-5f64,
        1.234567e-7,
        1.234567e-8,
        1.23456789012345e-8,
        1.23456789012345e-14,
        1.23456789012345e-15,
    ];
    // windows x86 run 38969737239, source 1bb3e065: the same value is
    // rendered in fixed notation only when its significant digits survive.
    let cases = [
        (0, false, "0.00001234567"),
        (0, true, "1.234567E-05"),
        (1, false, "0.0000001234567"),
        (1, true, "1.234567E-07"),
        (2, false, "0.00000001234567"),
        (2, true, "1.234567E-08"),
        (3, false, "1.23456789012345E-08"),
        (3, true, "1.234568E-08"),
        (4, false, "1.23456789012345E-14"),
        (4, true, "1.234568E-14"),
        (5, false, "1.23456789012345E-15"),
        (5, true, "1.234568E-15"),
    ];
    for (index, single, expected) in cases {
        let value = if single {
            Variant32::new(4, &(inputs[index] as f32).to_bits().to_le_bytes())
        } else {
            Variant32::new(5, &inputs[index].to_bits().to_le_bytes())
        };
        assert_eq!(
            value.number().unwrap().text().unwrap(),
            expected,
            "{index}/{single}"
        );
    }
}
