//! generic decoding of the already authenticated immutable v2 owner blob.
use crate::cpu::core::emitter::mem;
use wasm_encoder::{BlockType, Function, ValType};

// parameters are blob base and unsigned word index. no guest memory is read.
pub(super) fn emit() -> Function {
    let mut f = Function::new([(6, ValType::I32), (1, ValType::I64)]);
    let mut c = f.instructions();
    c.local_get(1)
        .local_get(0)
        .i32_load(mem(8, 0))
        .i32_lt_u()
        .if_(BlockType::Result(ValType::I64))
        .local_get(0)
        .i32_load(mem(12, 0))
        .local_set(2)
        .local_get(1)
        .local_get(2)
        .i32_mul()
        .local_tee(3)
        .i32_const(63)
        .i32_and()
        .local_set(4)
        .local_get(0)
        .local_get(3)
        .i32_const(6)
        .i32_shr_u()
        .i32_const(3)
        .i32_shl()
        .i32_add()
        .i64_load(mem(48, 0))
        .local_get(4)
        .i64_extend_i32_u()
        .i64_shr_u()
        .local_get(4)
        .local_get(2)
        .i32_add()
        .i32_const(64)
        .i32_gt_u()
        .if_(BlockType::Result(ValType::I64))
        .local_get(0)
        .local_get(3)
        .i32_const(6)
        .i32_shr_u()
        .i32_const(1)
        .i32_add()
        .i32_const(3)
        .i32_shl()
        .i32_add()
        .i64_load(mem(48, 0))
        .i32_const(64)
        .local_get(4)
        .i32_sub()
        .i64_extend_i32_u()
        .i64_shl()
        .else_()
        .i64_const(0)
        .end()
        .i64_or()
        .i64_const(1)
        .local_get(2)
        .i64_extend_i32_u()
        .i64_shl()
        .i64_const(1)
        .i64_sub()
        .i64_and()
        .i32_wrap_i64()
        .local_set(3)
        .local_get(0)
        .i32_load(mem(40, 0))
        .local_tee(5)
        .i32_eqz()
        .if_(BlockType::Result(ValType::I64))
        .local_get(0)
        .local_get(0)
        .i32_load(mem(28, 0))
        .i32_add()
        .local_get(3)
        .i32_const(3)
        .i32_shl()
        .i32_add()
        .i64_load(mem(0, 0))
        .else_()
        .local_get(0)
        .local_get(0)
        .i32_load(mem(28, 0))
        .i32_add()
        .local_get(3)
        .i32_const(4)
        .local_get(5)
        .i32_add()
        .i32_mul()
        .i32_add()
        .local_tee(6)
        .i32_load(mem(0, 0))
        .i64_extend_i32_u()
        .local_set(8)
        .local_get(5)
        .i32_const(1)
        .i32_eq()
        .if_(BlockType::Result(ValType::I32))
        .local_get(6)
        .i32_load8_u(mem(4, 0))
        .else_()
        .local_get(6)
        .i32_load16_u(mem(4, 0))
        .end()
        .local_set(7)
        .local_get(0)
        .local_get(0)
        .i32_load(mem(28, 0))
        .i32_add()
        .local_get(0)
        .i32_load(mem(20, 0))
        .i32_const(4)
        .local_get(5)
        .i32_add()
        .i32_mul()
        .i32_add()
        .local_get(7)
        .i32_const(2)
        .i32_shl()
        .i32_add()
        .i32_load(mem(0, 0))
        .i64_extend_i32_u()
        .i64_const(32)
        .i64_shl()
        .local_get(8)
        .i64_or()
        .end()
        .else_()
        .i64_const(0)
        .end()
        .end();
    f
}
