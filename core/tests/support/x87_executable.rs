use super::executable;

pub fn pe32() -> Vec<u8> {
    let mut bytes = executable::pe32(&[
        0xd9, 0x2d, 0x90, 0x21, 0x40, 0, 0xd9, 0x05, 0x80, 0x21, 0x40, 0, 0xd9, 0xfa, 0xd8, 0x3d,
        0x84, 0x21, 0x40, 0, 0xd9, 0x1d, 0x88, 0x21, 0x40, 0, 0xcc,
    ]);
    bytes[0x580..0x584].copy_from_slice(&4_f32.to_le_bytes());
    bytes[0x584..0x588].copy_from_slice(&8_f32.to_le_bytes());
    bytes[0x590..0x592].copy_from_slice(&0x027f_u16.to_le_bytes());
    bytes
}
