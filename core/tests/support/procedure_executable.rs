use super::imported_executable;

pub fn pe32() -> Vec<u8> {
    let mut bytes = imported_executable::pe32(
        &[
            0x68, 0x80, 0x21, 0x40, 0, 0xff, 0x15, 0x60, 0x20, 0x40, 0, 0x68, 0xa0, 0x21, 0x40, 0,
            0x50, 0xff, 0x15, 0x64, 0x20, 0x40, 0, 0x89, 0xc3, 0xff, 0xd0, 0xcc,
        ],
        "kernel32.dll",
        &["GetModuleHandleA", "GetProcAddress"],
    );
    bytes[0x580..0x58d].copy_from_slice(b"KERNEL32.dll\0");
    bytes[0x5a0..0x5ab].copy_from_slice(b"GetVersion\0");
    bytes
}
