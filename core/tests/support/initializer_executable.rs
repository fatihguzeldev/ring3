use super::imported_executable;

pub fn pe32(seed: u32) -> Vec<u8> {
    let mut code = vec![0xcc; 256];
    let entry = [
        0x68, 0x90, 0x21, 0x40, 0, 0x68, 0x80, 0x21, 0x40, 0, 0xff, 0x15, 0x60, 0x20, 0x40, 0,
        0x83, 0xc4, 8, 0xcc,
    ];
    code[..entry.len()].copy_from_slice(&entry);
    let mut first = vec![0xc7, 0x05, 0xc0, 0x21, 0x40, 0];
    first.extend_from_slice(&seed.to_le_bytes());
    first.extend_from_slice(&[0xc7, 0x05, 0x8c, 0x21, 0x40, 0, 0xc0, 0x10, 0x40, 0, 0xc3]);
    code[0x80..0x80 + first.len()].copy_from_slice(&first);
    let second = [
        0x83, 0x05, 0xc0, 0x21, 0x40, 0, 5, 0x68, 0xa4, 0x21, 0x40, 0, 0x68, 0xa0, 0x21, 0x40, 0,
        0xff, 0x15, 0x60, 0x20, 0x40, 0, 0x83, 0xc4, 8, 0xc3,
    ];
    code[0xa0..0xa0 + second.len()].copy_from_slice(&second);
    let third = [
        0xa1, 0xc0, 0x21, 0x40, 0, 0x01, 0xc0, 0xa3, 0xc0, 0x21, 0x40, 0, 0xc3,
    ];
    code[0xc0..0xc0 + third.len()].copy_from_slice(&third);
    let nested = [
        0x83, 0x05, 0xc0, 0x21, 0x40, 0, 3, 0xff, 0x15, 0x64, 0x20, 0x40, 0, 0xc3,
    ];
    code[0xe0..0xe0 + nested.len()].copy_from_slice(&nested);
    let mut bytes = imported_executable::pe32(&code, "MSVCRT.dll", &["_initterm", "__p__fmode"]);
    for (offset, pointer) in [
        (0x180, 0x0040_1080_u32),
        (0x188, 0x0040_10a0),
        (0x18c, 0xdead_beef),
        (0x1a0, 0x0040_10e0),
    ] {
        bytes[1024 + offset..1028 + offset].copy_from_slice(&pointer.to_le_bytes());
    }
    bytes
}
