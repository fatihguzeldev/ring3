use super::executable;

pub fn pe32() -> Vec<u8> {
    let mut bytes = executable::pe32(&[
        0x9b, 0xd9, 0x3d, 0x80, 0x21, 0x40, 0, 0x9b, 0xd9, 0x2d, 0x88, 0x21, 0x40, 0, 0x9b, 0xcc,
    ]);
    bytes[0x580..0x584].fill(0xaa);
    bytes[0x588..0x58a].copy_from_slice(&0x0f7f_u16.to_le_bytes());
    bytes
}
