use super::imported_executable;

pub fn pe32(mode: u32) -> Vec<u8> {
    let mut code = vec![0x68];
    code.extend_from_slice(&mode.to_le_bytes());
    code.extend_from_slice(&[
        0xff, 0x15, 0x60, 0x20, 0x40, 0, 0x89, 0xc3, 0xff, 0x15, 0x64, 0x20, 0x40, 0, 0x89, 0xc6,
        0x6a, 0, 0xff, 0x15, 0x60, 0x20, 0x40, 0, 0x89, 0xc7, 0xff, 0x15, 0x64, 0x20, 0x40, 0,
        0xcc,
    ]);
    imported_executable::pe32(&code, "KERNEL32.dll", &["SetErrorMode", "GetErrorMode"])
}
