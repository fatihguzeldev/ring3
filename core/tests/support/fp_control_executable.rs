use super::imported_executable;

pub fn pe32(initial: u16, value: u32, mask: u32) -> Vec<u8> {
    let mut code = vec![
        0xd9, 0x3d, 0, 0x23, 0x40, 0, 0x6a, 0, 0x6a, 0, 0xff, 0x15, 0x60, 0x20, 0x40, 0, 0x83,
        0xc4, 8, 0x89, 0xc3, 0xc7, 0x05, 4, 0x23, 0x40, 0,
    ];
    code.extend_from_slice(&u32::from(initial).to_le_bytes());
    code.extend_from_slice(&[0xd9, 0x2d, 4, 0x23, 0x40, 0, 0x68]);
    code.extend_from_slice(&mask.to_le_bytes());
    code.push(0x68);
    code.extend_from_slice(&value.to_le_bytes());
    code.extend_from_slice(&[
        0xff, 0x15, 0x60, 0x20, 0x40, 0, 0x83, 0xc4, 8, 0xd9, 0x3d, 8, 0x23, 0x40, 0, 0xcc,
    ]);
    imported_executable::pe32(&code, "MSVCRT.dll", &["_controlfp"])
}
