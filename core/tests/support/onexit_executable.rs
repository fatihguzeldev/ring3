use super::imported_executable;

pub fn pe32() -> Vec<u8> {
    let mut code = vec![
        0x68, 0x80, 0x10, 0x40, 0, 0xff, 0x15, 0x60, 0x20, 0x40, 0, 0x83, 0xc4, 4, 0x89, 0xc3,
        0x68, 0x90, 0x10, 0x40, 0, 0xff, 0x15, 0x60, 0x20, 0x40, 0, 0x83, 0xc4, 4, 0xcc,
    ];
    code.resize(160, 0xcc);
    for (offset, value) in [(128, 1), (144, 2)] {
        code[offset..offset + 11]
            .copy_from_slice(&[0xc7, 0x05, 0x80, 0x21, 0x40, 0, value, 0, 0, 0, 0xc3]);
    }
    imported_executable::pe32(&code, "MSVCRT.dll", &["_onexit"])
}
